const norm = w => String(w == null ? '' : w).replace(/[ً-ْـ]/g, '').replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي').replace(/[^ء-يa-z0-9 ]/gi, '').trim().replace(/^ال/, '');
const INDEX = [];
for (const [region, list] of Object.entries(CITIES)) for (const c of list) INDEX.push({ region, key: norm(c) });
INDEX.sort((a, b) => b.key.length - a.key.length);   // الأطول أول (مثل «المدينة المنورة» قبل «المدينة»)

// يرجّع اسم المنطقة أو null لو المدينة غير معروفة
function regionOf(city) {
  const n = norm(city); if (!n) return null;
  const exact = INDEX.find(x => x.key === n); if (exact) return exact.region;
  // تطابق كلمات كاملة فقط (ونتجاهل كلمة «مدينة» وحدها لأنها عامة)
  const padded = ' ' + n.split(' ').map(w => w.replace(/^ال/, '')).join(' ') + ' ';
  const hit = INDEX.find(x => x.key.length >= 3 && x.key !== 'مدينه' && padded.includes(' ' + x.key + ' '));
  return hit ? hit.region : null;
}

